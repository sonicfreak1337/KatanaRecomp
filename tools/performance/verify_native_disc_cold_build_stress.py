    require(provenance["retail_content"] is False, "Manifest darf keinen Retailinhalt ausweisen")
    require(provenance["source_inputs"] == [], "Manifest darf keine Quell-/Retailinputs besitzen")
    require(
        as_mapping(manifest["workload"], "Manifest-Workload") == expected_workload(profile),
        "Manifest-Workload besitzt nicht das exakte Profil",
    )
    formats = as_mapping(manifest["formats"], "Manifest-Formate")
    require(
        formats
        == {
            "root_header_size": 24,
            "root_magic": ROOT_MAGIC.decode("ascii"),
            "root_record_size": 20,
        },
        "Manifest-Formate stimmen nicht mit den Binaertabellen ueberein",
    )
    return manifest, profile


