def verify_iso_manifest(
    manifest: dict[str, Any],
    files: dict[str, bytes],
    entries_by_name: dict[str, DirectoryEntry],
) -> None:
    raw = field(manifest, ("iso_files",), "Manifest ISO-Dateien")
    entries = as_list(raw, "Manifest ISO-Dateien")
    manifest_order: list[str] = []
    described: dict[str, tuple[int, str]] = {}
    for index, raw_item in enumerate(entries):
        item = as_mapping(raw_item, f"Manifest ISO-Datei {index}")
        name = field(item, ("name", "path"), f"ISO-Datei {index} Name")
        require(isinstance(name, str) and name in files, f"Manifest beschreibt unbekannte ISO-Datei: {name}")
        size = exact_int(field(item, ("size", "size_bytes", "bytes"), f"ISO-Datei {name} Groesse"), f"ISO-Datei {name} Groesse")
        digest = field(item, ("sha256",), f"ISO-Datei {name} SHA-256")
        require(isinstance(digest, str) and SHA256_RE.fullmatch(digest) is not None, f"ISO-Datei {name}: SHA-256 ungueltig")
        extent_lba = exact_int(
            field(item, ("extent_lba",), f"ISO-Datei {name} Extent"),
            f"ISO-Datei {name} Extent",
        )
        require(
            extent_lba == entries_by_name[name].extent and extent_lba >= DATA_TRACK_LBA,
            f"ISO-Datei {name}: Manifest-Extent stimmt nicht",
        )
        require(name not in described, f"Manifest ISO-Datei doppelt: {name}")
        described[name] = (size, digest)
        manifest_order.append(name)
    require(manifest_order == sorted(manifest_order), "Manifest ISO-Dateien sind nicht sortiert")
    require(set(described) == set(files), "Manifest beschreibt nicht exakt alle ISO-Dateien")
    for name, data in files.items():
        size, digest = described[name]
        require(size == len(data) and digest == sha256_bytes(data), f"Manifest ISO-Datei {name} stimmt nicht")


