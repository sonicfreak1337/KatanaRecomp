def verify_modules(files: dict[str, bytes], profile: Profile) -> None:
    modules = sorted(name for name in files if MODULE_NAME_RE.fullmatch(name))
    expected_names = [f"M{index:03d}.BIN;1" for index in range(profile.modules)]
    require(modules == expected_names, "ISO besitzt falsche Latent-Modulmenge")
    expected_size = profile.chunks_per_module * profile.chunk_size
    require(profile.chunk_size % 4 == 0, "Profil-Chunkgroesse ist nicht SH-4-ausgerichtet")
    digests: set[str] = set()
    for name in modules:
        data = files[name]
        require(len(data) == expected_size, f"{name} besitzt falsche Groesse")
        digest = sha256_bytes(data)
        require(digest not in digests, f"{name} dupliziert bytegleich ein anderes Modul")
        digests.add(digest)
        terminal_offsets = {len(data) - 4}
        if name == "M000.BIN;1":
            terminal_offsets.add(len(data) // 2 - 4)
        for offset in range(0, len(data), 4):
            control = read_le16(data, offset)
            delay = read_le16(data, offset + 2)
            if offset in terminal_offsets:
                require(control == 0x000B, f"{name}: Abschluss ist kein rts")
                require(delay == 0x0009, f"{name}: rts-Delay-Slot ist kein nop")
            else:
                require(control == 0xA000, f"{name}: kein bra 0 bei {offset}")
                require(delay & 0xF000 == 0xE000, f"{name}: ungueltiger Delay-Slot")
    duplicate = files.get("M000DUP.BIN;1")
    require(duplicate is not None, "ISO besitzt keinen zweiten bytegleichen Modul-Extent")
    require(duplicate == files["M000.BIN;1"], "zweiter Modul-Extent ist nicht bytegleich")


def verify_latent_hints(
    data: bytes,
    files: dict[str, bytes],
    entries: dict[str, DirectoryEntry],
    profile: Profile,
) -> None:
    try:
        text = data.decode("ascii")
    except UnicodeDecodeError as error:
        raise VerificationError("latent-aot-entries.txt ist nicht ASCII") from error
    require("\r" not in text and text.endswith("\n"), "Latent-AOT-Hints brauchen kanonische LF-Zeilen")
    candidates = []
    for module_index in range(profile.modules):
        name = f"M{module_index:03d}.BIN;1"
        payload = files[name]
        entry_offsets = (0, len(payload) // 2) if module_index == 0 else (0,)
        for entry_offset in entry_offsets:
            candidates.append(
                (
                    sha256_bytes(payload),
                    entries[name].extent * LOGICAL_SECTOR_SIZE,
                    len(payload),
                    entry_offset,
                )
            )
    duplicate_name = "M000DUP.BIN;1"
    duplicate = files[duplicate_name]
    for entry_offset in (0, len(duplicate) // 2):
        candidates.append(
            (
                sha256_bytes(duplicate),
                entries[duplicate_name].extent * LOGICAL_SECTOR_SIZE,
                len(duplicate),
                entry_offset,
            )
        )
    expected_lines = [
        f"sha256:{digest}@{offset}:{size}:{entry_offset}"
        for digest, offset, size, entry_offset in sorted(candidates)
    ]
    require(
        text.splitlines() == expected_lines,
        "Latent-AOT-Hints stimmen nicht exakt mit den ISO-Modulen ueberein",
    )


def manifest_artifacts(manifest: dict[str, Any]) -> dict[str, tuple[int, str]]:
    raw = field(manifest, ("artifacts",), "Manifest-Artefakte")
    result: dict[str, tuple[int, str]] = {}
    if isinstance(raw, dict):
        items = []
        for path, metadata in raw.items():
            item = as_mapping(metadata, f"Manifest-Artefakt {path}").copy()
            item["path"] = path
            items.append(item)
    else:
        items = as_list(raw, "Manifest-Artefakte")
    for index, raw_item in enumerate(items):
        item = as_mapping(raw_item, f"Manifest-Artefakt {index}")
        path = relative_artifact_path(field(item, ("path", "name"), f"Artefakt {index} Pfad"), f"Artefakt {index} Pfad")
        size = exact_int(field(item, ("size", "size_bytes", "bytes"), f"Artefakt {path} Groesse"), f"Artefakt {path} Groesse")
        digest = field(item, ("sha256",), f"Artefakt {path} SHA-256")
        require(isinstance(digest, str) and SHA256_RE.fullmatch(digest) is not None, f"Artefakt {path} SHA-256 ungueltig")
        require(path not in result, f"Manifest-Artefakt doppelt: {path}")
        result[path] = (size, digest)
    return result


