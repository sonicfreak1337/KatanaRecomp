def snapshot(root: Path) -> dict[str, bytes]:
    result: dict[str, bytes] = {}
    for path in sorted(root.rglob("*")):
        info = path.lstat()
        require(stat.S_ISREG(info.st_mode) and not path.is_symlink(), f"Vergleich besitzt Nicht-Datei: {path}")
        relative = path.relative_to(root).as_posix()
        result[relative] = path.read_bytes()
    return result


def compare_fixtures(first: Fixture, second: Fixture) -> None:
    require(first.profile == second.profile, "--compare-Profile stimmen nicht ueberein")
    first_snapshot = snapshot(first.root)
    second_snapshot = snapshot(second.root)
    require(first_snapshot.keys() == second_snapshot.keys(), "--compare-Dateimengen stimmen nicht")
    for path, data in first_snapshot.items():
        require(data == second_snapshot[path], f"--compare ist nicht byteidentisch: {path}")


def run_disc_audit(executable: Path, fixture: Fixture) -> None:
    try:
        resolved = executable.resolve(strict=True)
    except OSError as error:
        raise VerificationError(f"--katana-cli fehlt: {executable}") from error
    require(resolved.is_file(), "--katana-cli ist keine regulaere Datei")
    try:
        completed = subprocess.run(
            [str(resolved), "disc-audit", str(fixture.root / "disc.gdi"), "--json"],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            timeout=120,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise VerificationError(f"disc-audit konnte nicht erfolgreich ausgefuehrt werden: {error}") from error
    stderr = completed.stderr.decode("utf-8", errors="replace").strip()
    require(completed.returncode == 0, f"disc-audit scheiterte ({completed.returncode}): {stderr}")
    try:
        report = json.loads(
            completed.stdout.decode("utf-8"),
            object_pairs_hook=unique_json_pairs,
            parse_constant=reject_json_constant,
        )
    except (UnicodeDecodeError, json.JSONDecodeError, TypeError) as error:
        raise VerificationError(f"disc-audit --json lieferte kein gueltiges JSON: {error}") from error
    require(isinstance(report, dict), "disc-audit --json lieferte kein JSON-Objekt")
    require(report.get("status") == "success", "disc-audit meldete keinen Erfolg")
    require(
        report.get("report_type") == "dreamcast_hardware_audit",
        "disc-audit lieferte den falschen Reporttyp",
    )


def build_argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("fixture", type=Path, help="Vom KR-4974-Writer erzeugtes Verzeichnis")
    parser.add_argument("--profile", choices=tuple(PROFILES), help="Erwartetes Profil (sonst Manifest)")
    parser.add_argument("--compare", type=Path, help="Zweite Ausgabe vollstaendig bytegenau vergleichen")
    parser.add_argument("--katana-cli", type=Path, help="Optional echten katana-recomp disc-audit --json ausfuehren")
    return parser


def main(argv: list[str] | None = None) -> int:
    arguments = build_argument_parser().parse_args(argv)
    try:
        fixture = verify_fixture(arguments.fixture, arguments.profile)
        compared = False
        if arguments.compare is not None:
            second = verify_fixture(arguments.compare, fixture.profile.name)
            compare_fixtures(fixture, second)
            compared = True
        audited = False
        if arguments.katana_cli is not None:
            run_disc_audit(arguments.katana_cli, fixture)
            audited = True
        result = {
            "basic_blocks": fixture.profile.basic_blocks,
            "byte_identical_compare": compared,
            "disc_audit": audited,
            "functions": fixture.profile.functions,
            "manifest_sha256": sha256_bytes(canonical_json(fixture.manifest)),
            "modules": fixture.profile.modules,
            "profile": fixture.profile.name,
            "roots": fixture.profile.roots,
            "schema": SCHEMA,
            "seed_waves": len(fixture.profile.wave_sizes),
            "verified": True,
        }
        sys.stdout.buffer.write(canonical_json(result))
        return 0
    except VerificationError as error:
        print(f"KR-4974-Verifikation fehlgeschlagen: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
