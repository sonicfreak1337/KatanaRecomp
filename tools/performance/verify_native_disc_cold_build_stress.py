    digest_bytes = read_regular(root / MANIFEST_DIGEST_NAME, "Manifest-Digest")
    expected_digest_text = f"sha256:{sha256_bytes(manifest_bytes)}\n".encode("ascii")
    require(digest_bytes == expected_digest_text, "Manifest-Digest stimmt nicht oder ist nicht kanonisch")
