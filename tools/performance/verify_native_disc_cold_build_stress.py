def require(condition: bool, message: str) -> None:
    if not condition:
        raise VerificationError(message)


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_regular(path: Path, description: str) -> bytes:
    try:
        info = path.lstat()
    except OSError as error:
        raise VerificationError(f"{description} fehlt: {path.name}") from error
    require(stat.S_ISREG(info.st_mode), f"{description} ist keine regulaere Datei: {path.name}")
    require(not path.is_symlink(), f"{description} darf kein Symlink sein: {path.name}")
    try:
        return path.read_bytes()
    except OSError as error:
        raise VerificationError(f"{description} konnte nicht gelesen werden: {path.name}") from error


def unique_json_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise VerificationError(f"JSON besitzt doppeltes Feld: {key}")
        result[key] = value
    return result


def reject_json_constant(value: str) -> None:
    raise VerificationError(f"JSON besitzt nicht-endlichen Zahlenwert: {value}")


def parse_json_bytes(data: bytes, description: str) -> Any:
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as error:
        raise VerificationError(f"{description} ist kein UTF-8") from error
    require("\r" not in text, f"{description} besitzt keine kanonischen LF-Zeilenenden")
    try:
        return json.loads(
            text,
            object_pairs_hook=unique_json_pairs,
            parse_constant=reject_json_constant,
        )
    except (json.JSONDecodeError, TypeError) as error:
        raise VerificationError(f"{description} ist kein gueltiges JSON: {error}") from error


def canonical_json(value: Any) -> bytes:
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode("utf-8")


def as_mapping(value: Any, description: str) -> dict[str, Any]:
    require(isinstance(value, dict), f"{description} muss ein JSON-Objekt sein")
    return value


def as_list(value: Any, description: str) -> list[Any]:
    require(isinstance(value, list), f"{description} muss ein JSON-Array sein")
    return value


def exact_int(value: Any, description: str) -> int:
    require(
        isinstance(value, int) and not isinstance(value, bool),
        f"{description} muss eine Ganzzahl sein",
    )
    return value


def relative_artifact_path(value: Any, description: str) -> str:
    require(isinstance(value, str) and value, f"{description} muss ein Dateiname sein")
    parsed = PurePosixPath(value)
    require(
        not parsed.is_absolute()
        and len(parsed.parts) == 1
        and parsed.parts[0] not in (".", "..")
        and "\\" not in value,
        f"{description} muss ein relativer Top-Level-Dateiname sein",
    )
    return value


def read_le16(data: bytes, offset: int) -> int:
    require(offset + 2 <= len(data), "Abgeschnittenes Little-Endian-16-Feld")
    return int.from_bytes(data[offset : offset + 2], "little")


def read_be16(data: bytes, offset: int) -> int:
    require(offset + 2 <= len(data), "Abgeschnittenes Big-Endian-16-Feld")
    return int.from_bytes(data[offset : offset + 2], "big")


def read_le32(data: bytes, offset: int) -> int:
    require(offset + 4 <= len(data), "Abgeschnittenes Little-Endian-32-Feld")
    return int.from_bytes(data[offset : offset + 4], "little")


def read_be32(data: bytes, offset: int) -> int:
    require(offset + 4 <= len(data), "Abgeschnittenes Big-Endian-32-Feld")
    return int.from_bytes(data[offset : offset + 4], "big")


def read_both16(data: bytes, offset: int, description: str) -> int:
    little = read_le16(data, offset)
    big = read_be16(data, offset + 2)
    require(little == big, f"{description}: Both-Endian-16-Werte widersprechen sich")
    return little


def read_both32(data: bytes, offset: int, description: str) -> int:
    little = read_le32(data, offset)
    big = read_be32(data, offset + 4)
    require(little == big, f"{description}: Both-Endian-32-Werte widersprechen sich")
    return little


def parse_directory_record(data: bytes, offset: int, description: str) -> tuple[DirectoryEntry, int]:
    require(offset < len(data), f"{description}: Directory-Offset liegt ausserhalb")
    length = data[offset]
    require(length >= 34, f"{description}: Directory-Record ist zu kurz")
    require(offset + length <= len(data), f"{description}: Directory-Record ist abgeschnitten")
    extent = read_both32(data, offset + 2, f"{description} Extent")
    size = read_both32(data, offset + 10, f"{description} Groesse")
    require(read_both16(data, offset + 28, f"{description} Volume") == 1, f"{description}: Volume != 1")
    name_length = data[offset + 32]
    require(33 + name_length <= length, f"{description}: Dateiname ist abgeschnitten")
    expected_length = 33 + name_length + (1 if name_length % 2 == 0 else 0)
    require(length == expected_length, f"{description}: nicht-kanonische Recordlaenge")
    name = data[offset + 33 : offset + 33 + name_length]
    return DirectoryEntry(name, extent, size, bool(data[offset + 25] & 0x02)), length


def parse_gdi(root: Path) -> tuple[bytes, bytes, bytes]:
    descriptor = read_regular(root / "disc.gdi", "GDI-Deskriptor")
    expected = (
        b"3\n"
        b"1 0 4 2352 track01.bin 0\n"
        b"2 30 0 2352 track02.raw 0\n"
        b"3 45000 4 2352 track03.bin 0\n"
    )
    require(descriptor == expected, "disc.gdi verletzt den kanonischen Drei-Track-Vertrag")
    low = read_regular(root / "track01.bin", "Low-Density-Datentrack")
    audio = read_regular(root / "track02.raw", "Audio-Track")
    high = read_regular(root / "track03.bin", "High-Density-Datentrack")
    require(len(low) == 24 * RAW_SECTOR_SIZE, "track01.bin muss genau 24 Rohsektoren besitzen")
    require(len(audio) == 4 * RAW_SECTOR_SIZE, "track02.raw muss genau vier Rohsektoren besitzen")
    require(
        len(high) >= 22 * RAW_SECTOR_SIZE and len(high) % RAW_SECTOR_SIZE == 0,
        "track03.bin besitzt keine gueltige Rohsektorgroesse",
    )
    return low, audio, high


def binary_coded_decimal(value: int) -> int:
    require(0 <= value <= 99, "BCD-Wert liegt ausserhalb")
    return ((value // 10) << 4) | (value % 10)


def mode1_payload(raw_track: bytes, description: str, first_lba: int) -> bytes:
    require(len(raw_track) % RAW_SECTOR_SIZE == 0, f"{description} ist nicht sektoral ausgerichtet")
    result = bytearray()
    for index in range(len(raw_track) // RAW_SECTOR_SIZE):
        sector = raw_track[index * RAW_SECTOR_SIZE : (index + 1) * RAW_SECTOR_SIZE]
        require(
            sector[:12] == b"\x00" + b"\xff" * 10 + b"\x00",
            f"{description} Sektor {index} besitzt keinen kanonischen Sync-Header",
        )
        absolute_frame = first_lba + index + 150
        expected_address = bytes(
            (
                binary_coded_decimal((absolute_frame // (75 * 60)) % 100),
                binary_coded_decimal((absolute_frame // 75) % 60),
                binary_coded_decimal(absolute_frame % 75),
            )
        )
        require(
            sector[12:15] == expected_address,
            f"{description} Sektor {index} besitzt eine falsche MSF-Adresse",
        )
        require(sector[15] == 1, f"{description} Sektor {index} ist kein Mode1-Sektor")
        require(
            all(byte == 0 for byte in sector[16 + LOGICAL_SECTOR_SIZE :]),
            f"{description} Sektor {index} besitzt nicht-kanonische Zusatzbytes",
        )
        result.extend(sector[16 : 16 + LOGICAL_SECTOR_SIZE])
    return bytes(result)


def verify_synthetic_low_track(logical: bytes) -> None:
    marker = (
        b"KATANA RECOMP SYNTHETIC LOW-DENSITY TRACK; "
        b"NO RETAIL CONTENT; KR-4974 CONTRACT 1\n"
    )
    require(len(logical) == 24 * LOGICAL_SECTOR_SIZE, "Low-Density-Nutzdatenlaenge falsch")
    for sector_index in range(24):
        expected = bytearray(LOGICAL_SECTOR_SIZE)
        expected[: len(marker)] = marker
        expected[128:132] = sector_index.to_bytes(4, "little")
        sector = logical[
            sector_index * LOGICAL_SECTOR_SIZE : (sector_index + 1) * LOGICAL_SECTOR_SIZE
        ]
        require(sector == expected, f"Low-Density-Sektor {sector_index} ist nicht oeffentlich synthetisch")


def verify_synthetic_audio(data: bytes) -> None:
    expected = bytearray(len(data))
    state = 0x00C0FFEE
    for index in range(len(expected)):
        state = (state * 1_664_525 + 1_013_904_223) & 0xFFFF_FFFF
        expected[index] = (state >> 24) & 0xFF
    require(data == expected, "Audio-Track stimmt nicht mit dem oeffentlichen LCG-Vertrag ueberein")


def translated_extent(extent: int, relative_extents: bool) -> int:
    if relative_extents:
        require(extent < DATA_TRACK_LBA, "ISO mischt relative und absolute Extents")
        return extent
    require(extent >= DATA_TRACK_LBA, "ISO mischt absolute und relative Extents")
    return extent - DATA_TRACK_LBA


def verify_path_table(
    logical: bytes,
    pvd: bytes,
    root_sector: int,
    relative_extents: bool,
) -> None:
    path_size = read_both32(pvd, 132, "ISO Path-Table-Groesse")
    require(path_size == 10, "ISO muss eine kanonische Eintrags-Path-Table besitzen")
    little_lba = read_le32(pvd, 140)
    big_lba = read_be32(pvd, 148)
    require(
        little_lba == DATA_TRACK_LBA + 18 and big_lba == DATA_TRACK_LBA + 19,
        "ISO Path-Tables muessen absolut auf Discsektor 45018/45019 liegen",
    )
    little_sector = translated_extent(little_lba, relative_extents)
    big_sector = translated_extent(big_lba, relative_extents)
    little = logical[little_sector * LOGICAL_SECTOR_SIZE : little_sector * LOGICAL_SECTOR_SIZE + path_size]
    big = logical[big_sector * LOGICAL_SECTOR_SIZE : big_sector * LOGICAL_SECTOR_SIZE + path_size]
    require(len(little) == path_size and len(big) == path_size, "ISO Path-Table ist abgeschnitten")
    require(little[0:2] == b"\x01\x00" and big[0:2] == b"\x01\x00", "ISO Root-Path-Record ungueltig")
    little_extent = read_le32(little, 2)
    big_extent = read_be32(big, 2)
    require(
        translated_extent(little_extent, relative_extents) == root_sector
        and translated_extent(big_extent, relative_extents) == root_sector,
        "ISO Path-Table verweist nicht auf Root",
    )
    require(read_le16(little, 6) == 1 and read_be16(big, 6) == 1, "ISO Root-Parent muss 1 sein")
    require(little[8:] == b"\x00\x00" and big[8:] == b"\x00\x00", "ISO Root-Pathname ungueltig")


def parse_iso(high: bytes) -> tuple[dict[str, bytes], dict[str, DirectoryEntry]]:
    logical = mode1_payload(high, "track03.bin", DATA_TRACK_LBA)
    require(len(logical) % LOGICAL_SECTOR_SIZE == 0, "Logische ISO ist nicht sektoral")
    volume_sectors = len(logical) // LOGICAL_SECTOR_SIZE
    ip = logical[:LOGICAL_SECTOR_SIZE]
    require(ip[0:16].rstrip(b" \0") == b"SEGA SEGAKATANA", "IP.BIN-Hardwarekennung ungueltig")
    require(ip[0x25:0x2B].rstrip(b" \0") == b"GD-ROM", "IP.BIN ist nicht als GD-ROM markiert")
    require(ip[0x3E] != ord("1"), "IP.BIN markiert einen nicht unterstuetzten WinCE-Boot")
    require(ip[0x60:0x70].rstrip(b" \0") == b"BOOT.BIN", "IP.BIN-Bootdateiname ungueltig")
    expected_bootstrap = bytes(
        (0x01, 0xD0, 0x2B, 0x40, 0x09, 0x00, 0x09, 0x00, 0x00, 0x00, 0x01, 0x8C)
    )
    require(ip[0x300 : 0x300 + len(expected_bootstrap)] == expected_bootstrap, "IP.BIN-Bootstrap ungueltig")

    pvd = logical[16 * LOGICAL_SECTOR_SIZE : 17 * LOGICAL_SECTOR_SIZE]
    terminator = logical[17 * LOGICAL_SECTOR_SIZE : 18 * LOGICAL_SECTOR_SIZE]
    require(pvd[0:7] == b"\x01CD001\x01", "ISO Primary Volume Descriptor ungueltig")
    require(terminator[0:7] == b"\xffCD001\x01", "ISO Volume Descriptor Terminator fehlt")
    require(read_both16(pvd, 128, "ISO Blockgroesse") == LOGICAL_SECTOR_SIZE, "ISO Blockgroesse != 2048")
    require(
        read_both32(pvd, 80, "ISO Volumegroesse") == DATA_TRACK_LBA + volume_sectors,
        "ISO absolute Volumegroesse falsch",
    )

    root_entry, _ = parse_directory_record(pvd, 156, "PVD-Root")
    require(root_entry.name == b"\x00" and root_entry.directory, "PVD-Rootrecord ungueltig")
    relative_extents = root_entry.extent < DATA_TRACK_LBA
    require(not relative_extents, "KR-4974-ISO muss absolute Disc-Extents verwenden")
    root_sector = translated_extent(root_entry.extent, relative_extents)
    require(root_sector == 20, "ISO Rootverzeichnis muss in Sektor 20 liegen")
    require(root_entry.size == LOGICAL_SECTOR_SIZE, "ISO Rootverzeichnis muss einen Sektor gross sein")
    verify_path_table(logical, pvd, root_sector, relative_extents)

    root_start = root_sector * LOGICAL_SECTOR_SIZE
    root_data = logical[root_start : root_start + root_entry.size]
    require(len(root_data) == root_entry.size, "ISO Rootverzeichnis ist abgeschnitten")
    entries: dict[str, DirectoryEntry] = {}
    offset = 0
    dot_names: list[bytes] = []
    while offset < len(root_data):
        if root_data[offset] == 0:
            require(all(byte == 0 for byte in root_data[offset:]), "ISO Rootpadding ist nicht null")
            break
        entry, length = parse_directory_record(root_data, offset, f"ISO Rootrecord {len(entries)}")
        if entry.name in (b"\x00", b"\x01"):
            dot_names.append(entry.name)
            require(entry.directory, "ISO Punktrecord ist kein Verzeichnis")
            require(
                translated_extent(entry.extent, relative_extents) == root_sector
                and entry.size == root_entry.size,
                "ISO Punktrecord verweist nicht auf Root",
            )
        else:
            try:
                name = entry.name.decode("ascii")
            except UnicodeDecodeError as error:
                raise VerificationError("ISO-Dateiname ist nicht ASCII") from error
            require(not entry.directory, f"Unerwartetes Unterverzeichnis: {name}")
            require(name not in entries, f"Doppelter ISO-Dateiname: {name}")
            require(re.fullmatch(r"[A-Z0-9_]{1,8}\.[A-Z0-9]{1,3};1", name) is not None, f"Unsicherer ISO-Dateiname: {name}")
            entries[name] = entry
        offset += length
    require(dot_names == [b"\x00", b"\x01"], "ISO Root braucht genau Punkt und Doppelpunkt")

    files: dict[str, bytes] = {}
    occupied: list[tuple[int, int, str]] = [(0, 21, "ISO-Systembereich")]
    for name, entry in sorted(entries.items()):
        sector = translated_extent(entry.extent, relative_extents)
        sector_count = (entry.size + LOGICAL_SECTOR_SIZE - 1) // LOGICAL_SECTOR_SIZE
        require(sector >= 21 and sector_count > 0, f"{name}: ungueltiger Datei-Extent")
        require(sector + sector_count <= volume_sectors, f"{name}: Datei-Extent liegt ausserhalb")
        for begin, end, previous_name in occupied:
            require(
                sector + sector_count <= begin or sector >= end,
                f"{name}: Datei-Extent ueberlappt {previous_name}",
            )
        occupied.append((sector, sector + sector_count, name))
        start = sector * LOGICAL_SECTOR_SIZE
        files[name] = logical[start : start + entry.size]
        padding = logical[start + entry.size : (sector + sector_count) * LOGICAL_SECTOR_SIZE]
        require(all(byte == 0 for byte in padding), f"{name}: Datei-Padding ist nicht null")
    ranges = sorted(occupied[1:])
    cursor = 21
    for begin, end, name in ranges:
        require(begin == cursor, f"ISO besitzt vor {name} eine unnoetige Extent-Luecke")
        cursor = end
    require(cursor == volume_sectors, "ISO besitzt nach dem letzten Extent unnoetige Sektoren")
    return files, entries


def expected_wave(profile: Profile, root_index: int) -> int:
    cursor = 0
    for wave, count in enumerate(profile.wave_sizes):
        cursor += count
        if root_index < cursor:
            return wave
    raise VerificationError(f"Root {root_index} liegt ausserhalb der Seed-Wellen")


def verify_boot(boot: bytes, profile: Profile) -> None:
    require(len(boot) == profile.functions * FUNCTION_SIZE, "BOOT.BIN besitzt falsche Groesse")
    resolution_roots = {
        (root_index * 37) % profile.functions for root_index in range(profile.roots)
    }
    require(
        len(resolution_roots) == profile.roots,
        "BOOT.BIN Resolution-Root-Menge ist nicht eindeutig",
    )
    for function_index in range(profile.functions):
        function = boot[function_index * FUNCTION_SIZE : (function_index + 1) * FUNCTION_SIZE]
        for block_index in range(BLOCKS_PER_FUNCTION):
            offset = block_index * 4
            control = read_le16(function, offset)
            delay = read_le16(function, offset + 2)
            if block_index + 1 == BLOCKS_PER_FUNCTION:
                require(control == 0x000B, f"BOOT Funktion {function_index}: Abschluss ist kein rts")
                require(
                    delay == 0x0009,
                    f"BOOT Funktion {function_index}: rts-Delay-Slot ist kein nop",
                )
            else:
                require(control == 0xA000, f"BOOT Funktion {function_index} Block {block_index}: kein bra 0")
                register = (function_index + block_index) & 0x0F
                immediate = (
                    function_index * 29
                    + block_index * 17
                    + DETERMINISTIC_SEED
                ) & 0xFF
                expected_delay = 0xE000 | (register << 8) | immediate
                if function_index in resolution_roots:
                    if block_index == RESOLUTION_PROBE_VALUE_BLOCK:
                        expected_delay = 0xE000 | immediate
                    elif block_index == RESOLUTION_PROBE_STORE_BLOCK:
                        expected_delay = 0x2F06
                    elif block_index == RESOLUTION_PROBE_LOAD_BLOCK:
                        expected_delay = 0x60F6
                require(
                    delay == expected_delay,
                    f"BOOT Funktion {function_index} Block {block_index}: "
                    "kein exakter deterministischer BRA-/Resolution-Delay-Slot",
                )


def verify_overrides(data: bytes, profile: Profile) -> None:
    try:
        text = data.decode("ascii")
    except UnicodeDecodeError as error:
        raise VerificationError("analysis.overrides ist nicht ASCII") from error
    require("\r" not in text and text.endswith("\n"), "analysis.overrides braucht kanonische LF-Zeilen")
    lines = text.splitlines()
    require(
        lines[:3]
        == [
            "version = 2",
            "schema = katana-analysis-directives",
            "mode = override",
        ],
        "analysis.overrides besitzt keinen kanonischen Header",
    )
    require(len(lines) == profile.functions + 3, "analysis.overrides besitzt falsche Funktionszahl")
    for index, line in enumerate(lines[3:]):
        match = OVERRIDE_RE.fullmatch(line)
        require(match is not None, f"analysis.overrides Zeile {index + 4} ungueltig")
        address = int(match.group(1), 16)
        size = int(match.group(2), 16)
        require(address == BOOT_ADDRESS + index * FUNCTION_SIZE, f"Override {index}: falsche Adresse")
        require(size == FUNCTION_SIZE, f"Override {index}: falsche Funktionsgroesse")


def verify_roots(data: bytes, profile: Profile) -> list[int]:
    header = struct.Struct("<8sIIII")
    record = struct.Struct("<IIIII")
    require(len(data) >= header.size, "ROOTS.BIN ist abgeschnitten")
    magic, version, count, record_size, wave_count = header.unpack_from(data)
    require(
        magic == ROOT_MAGIC and version == ROOT_SCHEMA_VERSION,
        "ROOTS.BIN Header ungueltig",
    )
    require(count == profile.roots and record_size == record.size, "ROOTS.BIN Counts ungueltig")
    require(wave_count == len(profile.wave_sizes), "ROOTS.BIN Wellenzahl ungueltig")
    require(len(data) == header.size + count * record.size, "ROOTS.BIN Groesse ungueltig")
    result: list[int] = []
    seen_functions: set[int] = set()
    for index in range(count):
        root_index, function_index, wave, expected_blocks, reserved = record.unpack_from(
            data, header.size + index * record.size
        )
        require(root_index == index, f"ROOTS.BIN Record {index}: instabiler Index")
        expected_function = (index * 37) % profile.functions
        require(function_index == expected_function, f"ROOTS.BIN Record {index}: falsche Funktion")
        expected_seed_wave = expected_wave(profile, index)
        require(wave == expected_seed_wave, f"ROOTS.BIN Record {index}: falsche Seed-Welle")
        require(
            expected_blocks == BLOCKS_PER_FUNCTION and reserved == 0,
            f"ROOTS.BIN Record {index}: kein reiner Realanalysevertrag",
        )
        require(function_index not in seen_functions, f"ROOTS.BIN Record {index}: Funktion dupliziert")
        seen_functions.add(function_index)
        result.append(function_index)
    return result


